// --- 3. HELPER FUNCTION ---

fun getCharDetails(char: String): CharDetail {
    val data = odiaDictionary[char]

    // Safety check: if data is missing, return placeholders
    if (data == null) {
        return CharDetail(listOf("ଉଦାହରଣ ନାହିଁ"), listOf("ଉଦାହରଣ ନାହିଁ"))
    }

    val wordsList = data.wordString.split(",").map { it.trim() }

    return CharDetail(
        words = wordsList,
        sentences = data.sentences
    )
}

